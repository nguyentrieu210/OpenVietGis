/** Scoped patch for an already-built live release; never promotes unrelated source changes. */
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import {createRequire} from "node:module";
const require=createRequire("/opt/openvietgis/apps/web/package.json");
const ts=require("typescript");
const [base,output,assetPrefix]=process.argv.slice(2);
assert.ok(base&&output&&assetPrefix);
assert.ok(!fs.existsSync(output),"Output must not exist");
assert.match(assetPrefix,/^\/rewrite\/assets\/ai-consent-[a-z0-9-]+\/$/);
const html=fs.readFileSync(path.join(base,"index.html"),"utf8");
const entry=html.match(/src="\/rewrite\/assets\/(index-[^"]+\.js)"/)?.[1];
const css=html.match(/href="\/rewrite\/assets\/(index-[^"]+\.css)"/)?.[1];
assert.ok(entry&&css,"Cannot identify exact release");
const src=fs.readFileSync(path.join(base,"assets",entry),"utf8");
const ast=ts.createSourceFile(entry,src,ts.ScriptTarget.ESNext,true,ts.ScriptKind.JS);
assert.equal(ast.parseDiagnostics.length,0);
const matches=ast.statements.filter(n=>ts.isFunctionDeclaration(n)&&n.name&&n.getText(ast).includes('data-ai="toggle"')&&n.getText(ast).includes("Đã kết nối phiên này"));
assert.equal(matches.length,1,"Expected exactly one AI panel");
const fn=matches[0];
const code=fs.readFileSync(new URL("./first-party.js",import.meta.url),"utf8").replace("export function mountAiCopilot(", "function "+fn.name.text+"(");
const patched=src.slice(0,fn.getStart(ast))+code+"\n"+src.slice(fn.end);
assert.equal(ts.createSourceFile(entry,patched,ts.ScriptTarget.ESNext,true,ts.ScriptKind.JS).parseDiagnostics.length,0);
fs.mkdirSync(output,{recursive:false});
fs.cpSync(path.join(base,"assets"),path.join(output,"assets"),{recursive:true});
fs.writeFileSync(path.join(output,"assets",entry),patched);
fs.appendFileSync(path.join(output,"assets",css),"\n"+fs.readFileSync(new URL("./first-party.css",import.meta.url),"utf8"));
fs.writeFileSync(path.join(output,"index.html"),html.replaceAll("/rewrite/assets/",assetPrefix));
console.log("Scoped AI panel hotfix:",entry,css,fn.name.text);
