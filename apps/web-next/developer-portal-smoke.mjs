import {chromium} from "@playwright/test";
import assert from "node:assert/strict";
import {generateKeyPairSync,sign,verify} from "node:crypto";
import {readFileSync} from "node:fs";
const host=process.env.OVG_DEVELOPER_BROWSER_URL;
const base=process.env.OVG_DEVELOPER_TEST_API;
const url=host+"/rewrite/?developer=1";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const canonical=x=>JSON.stringify(x,(_key,value)=>value&&typeof value==="object"&&!Array.isArray(value)?Object.fromEntries(Object.keys(value).sort().map(k=>[k,value[k]])):value);
const keys=generateKeyPairSync("ed25519");
const publicKey=keys.publicKey.export({format:"der",type:"spki"}).subarray(-32).toString("base64");
const signature=x=>sign(null,Buffer.from(canonical(x)),keys.privateKey).toString("base64");
const errors=[];
async function authenticated(cookie){
 const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
 await context.addCookies([{name:"ovg_session",value:cookie,url:host}]);
 const page=await context.newPage();
 page.on("pageerror",e=>errors.push(e.message));
 await page.route(host+"/api/v1/**",async route=>{
  const r=route.request();const u=new URL(r.url());
  const headers={...r.headers(),cookie:"ovg_session="+cookie};delete headers.host;delete headers["content-length"];
  const response=await route.fetch({url:base+u.pathname+u.search,headers,maxRedirects:0});
  await route.fulfill({response});
 });
 await page.goto(url,{waitUntil:"domcontentloaded"});
 return page;
}
try{
 const dev=await authenticated(process.env.OVG_DEVELOPER_TEST_SESSION);
 await dev.getByRole("heading",{name:"1. Đăng ký nhà phát triển"}).waitFor({timeout:25000});
 const uid=await dev.getByLabel("Mã tài khoản").inputValue();
 const registration={name:"Browser reference publisher",public_key:publicKey};
 await dev.getByLabel("JSON đăng ký đã ký").fill(JSON.stringify({...registration,proof:signature({purpose:"openvietgis.publisher.v1",user_id:uid,...registration})}));
 await dev.getByRole("button",{name:"Đăng ký nhà phát triển"}).click();
 await dev.getByRole("heading",{name:registration.name}).waitFor();
 const label=await dev.locator(".publisher-profile code").innerText();
 const pid=label.slice(8,-1);
 assert.match(pid,/^dev_[a-f0-9]{24}$/);
 await dev.getByLabel("URL plugin HTTPS").fill("https://plugins.example.com/releases/v1/index.html");
 const downloaded=dev.waitForEvent("download");
 await dev.getByRole("button",{name:"Tải manifest.json"}).click();
 const file=await downloaded,manifest=JSON.parse(readFileSync(await file.path(),"utf8"));
 assert.equal(manifest.extension_key,"partner_"+pid+"_inspector");
 const body={publisher_id:pid,manifest};
 await dev.getByLabel("JSON phiên bản đã ký").fill(JSON.stringify({...body,signature:signature(body)}));
 await dev.getByRole("button",{name:"Gửi xét duyệt"}).click();
 await dev.getByText("Chờ xét duyệt",{exact:true}).waitFor();
 assert.equal(await dev.getByRole("button",{name:"Xét duyệt Marketplace"}).count(),0);
 console.log("PASS publisher proof, manifest builder, signed submission in real browser");
 const reviewer=await authenticated(process.env.OVG_DEVELOPER_REVIEW_SESSION);
 await reviewer.getByRole("button",{name:"Xét duyệt Marketplace"}).click();
 const card=reviewer.locator(".publisher-release").filter({hasText:manifest.extension_key});
 await card.waitFor({timeout:25000});
 await card.getByLabel("Biên bản / lý do xét duyệt").fill("Browser review evidence");
 await card.getByRole("button",{name:"Duyệt phiên bản"}).click();
 await reviewer.getByText("Không có hồ sơ trong trạng thái này.").waitFor();
 await reviewer.getByLabel("Trạng thái").selectOption("approved");
 await card.waitFor();
 const exported=reviewer.waitForEvent("download");
 await card.getByRole("button",{name:"Xuất bản ghi đã duyệt"}).click();
 const entry=JSON.parse(readFileSync(await (await exported).path(),"utf8"));
 assert.deepEqual(entry.releases[0].manifest,manifest);
 assert.equal(entry.publishers[0].id,pid);
 assert.ok(verify(null,Buffer.from(canonical(body)),keys.publicKey,Buffer.from(entry.releases[0].signature,"base64")));
 await dev.getByRole("button",{name:"Làm mới",exact:true}).click();
 await dev.getByText("Đã duyệt · Chờ ký catalog",{exact:true}).waitFor();
 await dev.getByText(/Browser review evidence/).waitFor();
 assert.equal(await dev.getByText("Đã phát hành",{exact:true}).count(),0);
 assert.equal(errors.length,0,errors.join("\n"));
 console.log("PASS separate reviewer, decision feedback, approved export, no false publication");
}finally{await browser.close()}
